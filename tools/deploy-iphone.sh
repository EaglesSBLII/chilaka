#!/bin/bash
# One-command iPhone deployment: hosts the PWA + deploys the sync server,
# both on a free Cloudflare account, then rebuilds everything with the sync
# endpoint baked in and prints the install URL.
#
#   bash tools/deploy-iphone.sh
#
# First run: a browser window opens to log in to (or create) a free
# Cloudflare account — click Allow, everything else is automatic.
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

echo "== Chilaka iPhone deploy =="

# 1. wrangler (local install, no global pollution)
if ! npx --yes wrangler --version >/dev/null 2>&1; then
  echo "installing wrangler…"
fi

# 2. login (wrangler whoami exits 0 even when logged OUT — check the words)
WHOAMI=$(npx --yes wrangler whoami 2>&1 || true)
if ! echo "$WHOAMI" | grep -qiE "you are logged in|associated with"; then
  echo ""
  echo "→ A browser window will now open."
  echo "  • No Cloudflare account? Click 'Sign up' (free, no card), then return."
  echo "  • Then click 'Allow' when asked to authorize Wrangler."
  echo ""
  npx --yes wrangler login
  WHOAMI=$(npx --yes wrangler whoami 2>&1 || true)
  if ! echo "$WHOAMI" | grep -qiE "you are logged in|associated with"; then
    echo "Login didn't complete — run this script again and finish the browser step."
    exit 1
  fi
fi
echo "logged in to Cloudflare."

# 3. KV namespace for the sync worker (idempotent)
cd "$ROOT/sync-worker"
if grep -q PLACEHOLDER_KV_ID wrangler.toml; then
  echo "creating KV namespace…"
  OUT=$(npx --yes wrangler kv namespace create SYNC 2>&1 || true)
  KV_ID=$(echo "$OUT" | grep -oE '[0-9a-f]{32}' | head -1)
  if [ -z "$KV_ID" ]; then echo "could not create KV namespace:"; echo "$OUT"; exit 1; fi
  sed -i '' "s/PLACEHOLDER_KV_ID/$KV_ID/" wrangler.toml
  echo "KV namespace: $KV_ID"
fi

# 4. deploy the sync worker
echo "deploying sync worker…"
DEPLOY_OUT=$(npx --yes wrangler deploy 2>&1)
echo "$DEPLOY_OUT" | tail -3
SYNC_URL=$(echo "$DEPLOY_OUT" | grep -oE 'https://[a-z0-9.-]+\.workers\.dev' | head -1)
if [ -z "$SYNC_URL" ]; then echo "could not find worker URL"; exit 1; fi
echo "sync server: $SYNC_URL"

# 5. bake the sync endpoint into the app
cd "$ROOT"
cat > app/src/sync-config.ts << EOF
// Generated by tools/deploy-iphone.sh — the deployed sync server.
// The endpoint alone grants no access — data lives under an unguessable
// 224-bit key that only your paired devices hold.
export const SYNC_ENDPOINT = '$SYNC_URL';
EOF

# 6. build the PWA and deploy to Cloudflare Pages
echo "building the app…"
npm run build -w app >/dev/null
echo "deploying the PWA…"
PAGES_OUT=$(npx --yes wrangler pages deploy app/dist --project-name chilaka --commit-dirty=true 2>&1 || npx --yes wrangler pages project create chilaka --production-branch main >/dev/null 2>&1 && npx --yes wrangler pages deploy app/dist --project-name chilaka --commit-dirty=true 2>&1)
echo "$PAGES_OUT" | tail -2
PWA_URL=$(echo "$PAGES_OUT" | grep -oE 'https://[a-z0-9.-]+\.pages\.dev' | head -1)

echo
echo "======================================================"
echo "  iPhone install URL:  ${PWA_URL:-<see output above>}"
echo "  Sync server:         $SYNC_URL"
echo "======================================================"
echo
echo "Next steps:"
echo "  1. Rebuild the Mac app so it gets the sync endpoint too:"
echo "       cd desktop && npm run dist   (or ask Claude to do it)"
echo "  2. iPhone: open the URL in Safari → Share → Add to Home Screen."
echo "  3. Mac app: Settings → Sync → Turn on sync → copy pairing code."
echo "  4. iPhone: Settings → Sync → paste code → Pair. Done."
